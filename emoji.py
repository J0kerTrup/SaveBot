"""Премиум-эмодзи из набора t.me/addemoji/RestrictedEmoji.

Telegram показывает их, если у владельца бота есть Premium; иначе клиент рисует обычный эмодзи, который лежит внутри.
Новый эмодзи — добавь пару «эмодзи: id» (id: bot.get_sticker_set("RestrictedEmoji")).
"""

import re

IDS: dict[str, str] = {
    "👋": "5472055112702629499",
    "📎": "5377844313575150051",
    "👥": "5372926953978341366",
    "🌍": "5399898266265475100",
    "🤖": "5372981976804366741",
    "➕": "5226945370684140473",
    "✅": "5427009714745517609",
    "❌": "5465665476971471368",
    "❗️": "5467928559664242360",
    "📥": "5433811242135331842",
    "👇": "5470177992950946662",
    "🎵": "5188621441926438751",
    "🇷🇺": "5449408995691341691",
    "🇺🇦": "5447309366568953338",
    "🇬🇧": "5202196682497859879",
    "🇪🇸": "5201957744877248121",
    "🇧🇷": "5202074005346983800",
    "🇹🇷": "5226948110873278599",
}

_RE = re.compile("|".join(re.escape(e) for e in sorted(IDS, key=len, reverse=True)))


def premium(text: str) -> str:
    """Текст для parse_mode HTML: известные эмодзи заменены премиум-версиями."""
    return _RE.sub(lambda m: f'<tg-emoji emoji-id="{IDS[m.group()]}">{m.group()}</tg-emoji>', text)


def split_icon(text: str) -> tuple[str | None, str]:
    """Кнопка «🇷🇺 Русский» → (id премиум-эмодзи, «Русский»); без известного эмодзи в начале — (None, текст)."""
    m = _RE.match(text)
    if not m:
        return None, text
    return IDS[m.group()], text[m.end() :].lstrip()
